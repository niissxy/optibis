export function getPortfolioBySlug(slug) {
  if (!slug) return null;
  return PORTFOLIO_DATA[slug] || Object.values(PORTFOLIO_DATA).find((p) => p.slug === slug || p.name.toLowerCase() === slug.toLowerCase());
}

export function getAllPortfolios() {
  return Object.values(PORTFOLIO_DATA);
}

export function getOtherPortfolios(currentSlug, limit = 3) {
  return Object.values(PORTFOLIO_DATA)
    .filter((p) => p.slug !== currentSlug)
    .slice(0, limit);
}